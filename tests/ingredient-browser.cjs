const {chromium}=require('@playwright/test');
const assert=require('node:assert/strict');
const base='http://127.0.0.1:8000';
const testName='Browser ingredient test breakfast';
(async()=>{
 const get=async q=>(await (await fetch(base+'/api/foods?q='+encodeURIComponent(q))).json()).foods;
 const egg=(await get('Egg whole raw fresh')).find(f=>f.name==='Egg, whole, raw, fresh');
 const white=(await get('Egg white raw fresh')).find(f=>f.name==='Egg, white, raw, fresh');
 const cheddar=(await get('Cheese cheddar reduced fat')).find(f=>f.name==='Cheese, Cheddar, reduced fat');
 const omelet=(await get('omelet cheese')).find(f=>f.id==='2707212');
 const item=(id,food,grams)=>({id,food,grams,quantityKind:'estimated',portionLabel:'Your quantity'});
 const corrected=[item('egg',egg,88),item('white',white,30),item('cheese',cheddar,25)];
 const total=key=>corrected.reduce((sum,i)=>sum+i.food.nutrients[key]*i.grams/100,0);
 const cleanup=async()=>{for(const f of await (await fetch(base+'/api/favorites')).json())if(f.name===testName)await fetch(base+'/api/favorites/'+f.id,{method:'DELETE'})};
 await cleanup();
 const browser=await chromium.launch({headless:true,executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'});
 try{
  const page=await browser.newPage({viewport:{width:1231,height:800}});
  const errors=[];page.on('pageerror',e=>errors.push(String(e)));
  let partial=false;
  await page.route('**/api/recognize',route=>route.fulfill({json:partial?{foods:[{label:'Cheese omelette',query:'omelet',visibleCount:1,estimatedGrams:200,components:[{label:'Cheddar cheese',query:'Cheese cheddar reduced fat',quantity:25,unit:'g',estimatedGrams:25}],matches:[],matchType:'partial'}],items:[item('egg',egg,88)],groups:[{id:'0',itemIds:['egg'],visible:1,logged:1}],missing:['Cheddar cheese'],usuals:[],description:'Omelette with unmatched cheese',question:'',notice:'Partial'}:{foods:[{label:'Cheese omelette',query:'omelet',estimatedGrams:200,visibleCount:1,matches:[omelet],matchType:'approximate'}],items:[item('whole',omelet,200)],groups:[{id:'0',itemIds:['whole'],visible:1,logged:1}],missing:[],usuals:[],description:'Cheese omelette',question:'How many eggs did you use?',notice:'Estimate'}}));
  let release;
  await page.route('**/api/refine',async route=>{
   const body=route.request().postDataJSON();
   if(body.message==='2 medium eggs,30g egg whites,25g reduced fat cheddar')assert.equal(body.pendingQuestion,'How many eggs did you use?');
   if(body.message==='bakery name only'){await route.fulfill({json:{items:null,message:'No product nutrition found; the generic estimate is unchanged.',question:'Do you have a nutrition label?',version:body.version}});return}
   if(body.message==='delayed correction')await new Promise(resolve=>release=resolve);
   await route.fulfill({json:{items:corrected,totals:{calories:total('calories')},message:'Updated the eggs, egg whites and reduced-fat cheddar.',question:'',version:body.version}});
  });
  await page.goto(base);
  const upload={name:'test.png',mimeType:'image/png',buffer:Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jRZkAAAAASUVORK5CYII=','base64')};
  await page.getByLabel('Upload meal photo').setInputFiles(upload);
  await page.getByLabel('Estimated macros').waitFor();
  assert.equal(await page.locator('.calories').first().innerText(),'342kcal');
  await page.getByText('How many eggs did you use?',{exact:true}).click();
  await page.getByLabel('Refine meal').fill('2 medium eggs,30g egg whites,25g reduced fat cheddar');
  await page.getByRole('button',{name:'Update',exact:true}).click();
  await page.getByText('Estimate recalculated. Updated the eggs, egg whites and reduced-fat cheddar.',{exact:true}).waitFor();
  assert.equal(await page.locator('.calories').first().innerText(),`${Math.round(total('calories'))}kcal`);
  await page.getByText('Adjust estimate',{exact:true}).click();
  assert.equal(await page.locator('.ingredient').count(),3);
  await page.getByRole('button',{name:'Undo last correction',exact:true}).click();
  assert.equal(await page.locator('.calories').first().innerText(),'342kcal');
  await page.getByLabel('Refine meal').fill('same correction');
  await page.getByRole('button',{name:'Update',exact:true}).click();
  await page.getByText('Estimate recalculated. Updated the eggs, egg whites and reduced-fat cheddar.',{exact:true}).waitFor();
  await page.getByLabel('Refine meal').fill('bakery name only');
  await page.getByRole('button',{name:'Update',exact:true}).click();
  await page.getByText('No product nutrition found; the generic estimate is unchanged.',{exact:true}).first().waitFor();
  assert.equal(await page.locator('.calories').first().innerText(),`${Math.round(total('calories'))}kcal`);
  // Late correction must not override manual edits made while it runs.
  await page.getByLabel('Refine meal').fill('delayed correction');
  await page.getByRole('button',{name:'Update',exact:true}).click();
  await page.waitForTimeout(100);
  await page.getByLabel('Portion in grams',{exact:true}).fill('100');
  release();
  await page.getByText('The meal changed while that correction was processing. Please send it again.',{exact:true}).waitFor();
  assert.equal(await page.getByLabel('Portion in grams',{exact:true}).inputValue(),'100');
  await page.getByLabel('Meal name',{exact:true}).fill(testName);
  await page.getByRole('button',{name:'Remember this meal',exact:true}).click();
  await page.getByText('Meal remembered. You can reuse it without another AI estimate.',{exact:true}).waitFor();
  await page.reload();
  await page.getByText('Your usual meals',{exact:true}).click();
  await page.getByRole('button',{name:new RegExp('^'+testName+' ')}).click();
  await page.getByText('Your saved meal',{exact:true}).waitFor();
  await page.getByText('Adjust estimate',{exact:true}).click();
  assert.equal(await page.getByLabel('Portion in grams',{exact:true}).inputValue(),'100');
  partial=true;
  await page.getByLabel('Upload meal photo').setInputFiles(upload);
  await page.getByRole('button',{name:'Cheddar cheese · find match',exact:true}).waitFor();
  assert.equal(await page.getByRole('button',{name:'Save meal',exact:true}).isEnabled(),false);
  await page.getByRole('button',{name:'Cheddar cheese · find match',exact:true}).click();
  await page.locator('.food-result').filter({hasText:cheddar.name}).first().click();
  assert.equal(await page.locator('.ingredient').count(),2);
  assert.equal(await page.getByRole('button',{name:'Save meal',exact:true}).isEnabled(),true);
  await page.getByText('Adjust estimate',{exact:true}).click();
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  await page.screenshot({path:'test-results/ingredient-correction.png',fullPage:true});
  assert.deepEqual(errors,[]);
  console.log('PASS: source-backed correction, undo, stale-response protection, remembered-meal persistence/recall, mobile layout. Provider responses simulated; no photos sent.');
 }finally{await browser.close();await cleanup()}
})().catch(e=>{console.error(e);process.exit(1)});
