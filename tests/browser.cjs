const { chromium } = require('@playwright/test');
const assert = require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:"/Applications/Google Chrome.app/Contents/MacOS/Google Chrome"});
 const page=await browser.newPage({viewport:{width:1440,height:1000}});
 const errors=[];page.on('pageerror',e=>errors.push(String(e)));
 for(const m of await (await fetch('http://127.0.0.1:8000/api/meals')).json()) if(m.name==='Browser test lunch') await fetch('http://127.0.0.1:8000/api/meals/'+m.id,{method:'DELETE'});
 await page.goto('http://127.0.0.1:8000');
 await page.getByRole('button',{name:'Log a meal',exact:true}).first().click();
 await page.getByPlaceholder('Search a dish, food or meal…').fill('rice white long-grain');
 await page.getByRole('button',{name:'Search foods',exact:true}).click();
 await page.getByRole('button',{name:/Rice, white, long-grain, regular, enriched, cooked/}).click();
 await page.getByLabel('Portion in grams').fill('150');
 await page.getByLabel('Meal name').fill('Browser test lunch');
 await page.getByRole('button',{name:'Save meal',exact:true}).click();
 await page.getByText('Browser test lunch',{exact:true}).waitFor();
 await page.reload();
 await page.getByText('Browser test lunch',{exact:true}).waitFor();
 await page.getByRole('button',{name:'Edit Browser test lunch'}).click();
 await page.getByLabel('Portion in grams').fill('200');
 await page.getByRole('button',{name:'Save meal',exact:true}).click();
 await page.getByText('Browser test lunch',{exact:true}).waitFor();
 assert.equal(await page.getByText('Browser test lunch',{exact:true}).count(),1);
 await page.screenshot({path:'test-results/desktop.png',fullPage:true});
 await page.getByRole('button',{name:'Delete Browser test lunch'}).click();
 await page.getByText('Browser test lunch',{exact:true}).waitFor({state:'detached'});
 assert.equal(await page.getByText('Browser test lunch',{exact:true}).count(),0);
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:'test-results/mobile.png',fullPage:true});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
 assert.deepEqual(errors,[]);
 await browser.close();console.log('PASS: search → portion → save → reload → edit → delete; mobile layout; no browser errors');
})().catch(e=>{console.error(e);process.exit(1)});
